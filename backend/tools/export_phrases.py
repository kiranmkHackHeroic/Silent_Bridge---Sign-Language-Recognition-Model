"""Write docs/PHRASES.md from the phrase dictionary (single source of truth: data/kannada_sign_mapping.json).

Usage (from backend/):  python tools/export_phrases.py
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.config import KANNADA_MAPPING_FILE, LABELS_FILE  # noqa: E402
from app.training.registry import active_paths, active_version  # noqa: E402
from app.translation.kannada_mapping import Vocabulary  # noqa: E402

ORDER = ["Greetings", "Introductions", "Education and college", "Family", "Food and water", "Travel and directions",
         "Common questions", "Assistance", "Health and emergencies", "Numbers and time", "Everyday responses"]


def main():
    vocab = Vocabulary(LABELS_FILE)
    classes = set(json.loads(active_paths()[1].read_text(encoding="utf-8"))["classes"])
    entries = json.loads(KANNADA_MAPPING_FILE.read_text(encoding="utf-8"))["entries"]
    by = defaultdict(list)
    for e in entries.values():
        if e.get("category"):
            gloss = " ".join((vocab.get(s).isl_gloss if vocab.get(s) else s.upper()) for s in e["sign_ids"])
            by[e["category"]].append((e["display"], e["english"], gloss, set(e["sign_ids"]) <= classes,
                                      [s for s in e["sign_ids"] if s not in classes]))
    total = sum(len(v) for v in by.values())
    rec = sum(r[3] for v in by.values() for r in v)
    out = ["# Supported Kannada phrases", "",
           f"Generated by `backend/tools/export_phrases.py` from `backend/data/kannada_sign_mapping.json`. **Camera** = every sign in",
           f"the sequence is a class of the active model `{active_version()}`, so the phrase can be recognised live; the",
           "others work only in Kannada → Sign. **All entries are unverified**: the Kannada wording is AI-assisted and the",
           "ISL sign order is a proposal, both pending review by a native Kannada speaker and an ISL user. Where ISL marks",
           "the meaning with the face (statement vs question) or with direction, both readings are listed for the same",
           "signs and the translator reports the sequence as ambiguous.", "",
           f"Total: **{total} phrases, {rec} recognisable from the camera.**", ""]
    for c in ORDER + sorted(set(by) - set(ORDER)):
        if c not in by:
            continue
        out += [f"## {c}", "", "| Kannada | English meaning | ISL sign sequence | Camera |", "|---|---|---|---|"]
        out += [f"| {kn} | {en} | {gl} | {'yes' if ok else 'no: ' + ', '.join(miss) + ' not trained'} |" for kn, en, gl, ok, miss in by[c]]
        out.append("")
    out += ["## Not supported", "",
            "- **Numbers:** the datasets used contain no number signs, so there are no number phrases.",
            "- **Travel and directions from the camera:** GO, WHERE and HOME are not in the trained vocabulary.", ""]
    path = Path(__file__).resolve().parents[2] / "docs" / "PHRASES.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}: {total} phrases, {rec} recognisable")


if __name__ == "__main__":
    main()
